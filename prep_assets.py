# Builds compact (50% scale) sprite sheets + sheets.json + boss cutouts for the horde prototype.
import json,glob,os
from PIL import Image,ImageDraw
SRC='/workspace/art/v2/char_sheet'; OUT='assets/chars'
JOBS={'kni':'騎士','lnc':'槍兵','mer':'商人','mnk':'武僧','acl':'服事','arc':'法師','rgr':'遊俠','brd':'吟遊','dnc':'舞者','gun':'槍手','hsn':'刺客'}
ATK={'attack_slash':'melee','attack_thrust':'melee','attack_chop':'melee','attack_fist':'melee','attack_whip':'melee','attack_staff':'magic','attack_shoot':'range','attack_play':'magic'}
out={}
for j in JOBS:
    sj=json.load(open(f'{SRC}/{j}/sheet.json'))
    for key,v in sj.items():
        f=f'{SRC}/{j}/{v["file"]}'
        im=Image.open(f).convert('RGBA'); n=v['frames']; cw=im.width/n; ch=im.height
        s=0.5
        im2=im.resize((int(im.width*s),int(ch*s)),Image.LANCZOS)
        name=v['file']; im2.save(f'{OUT}/{name}',quality=76,method=6)
        acts=v['actions']; atk=[a for a in acts if a in ATK]
        a0=('attack_shoot' if 'attack_shoot' in atk else atk[0])
        out[key]={'file':name,'cw':cw*s,'ch':ch*s,'base':v['baseline_y']*s,'job':j,'jobname':JOBS[j],'atk':ATK[a0],
          'act':{k:{'s':acts[k]['start'],'n':acts[k]['count'],'fps':acts[k]['fps']} for k in ['idle','walk','hit','down','chant','release']},
          'attack':{'s':acts[a0]['start'],'n':acts[a0]['count'],'fps':acts[a0]['fps']}}
        print(key,im2.size,os.path.getsize(f'{OUT}/{name}')//1024,'KB',a0)
json.dump(out,open(f'{OUT}/sheets.json','w'),ensure_ascii=False)
# NOTE: boss cutouts (hills_boss, cave_boss, magma_boss) were produced earlier from /workspace/art/v2/ref/mob; mobs are generated by tools/gen_mobs.py.
for b in ['hills_boss','cave_boss','magma_boss']:
    im=Image.open(f'/workspace/art/v2/ref/mob/{b}.png').convert('RGBA')
    w,h=im.size
    mask=Image.new('L',(w,h),0)
    px=im.load()
    # flood from borders over near-white
    import collections
    seen=bytearray(w*h);q=collections.deque()
    def ok(x,y): r,g,b_,a=px[x,y];return r>228 and g>228 and b_>228
    for x in range(w):
        for y in (0,h-1):
            if ok(x,y): q.append((x,y));seen[y*w+x]=1
    for y in range(h):
        for x in (0,w-1):
            if ok(x,y) and not seen[y*w+x]: q.append((x,y));seen[y*w+x]=1
    while q:
        x,y=q.popleft();px[x,y]=(255,255,255,0)
        for dx,dy in((1,0),(-1,0),(0,1),(0,-1)):
            nx,ny=x+dx,y+dy
            if 0<=nx<w and 0<=ny<h and not seen[ny*w+nx] and ok(nx,ny): seen[ny*w+nx]=1;q.append((nx,ny))
    im=im.crop(im.getbbox())
    im.save(f'assets/mobs/{b}.webp',quality=82)
    print(b,im.size)
